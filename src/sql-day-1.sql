--JOINS
--Inner join -> fetching the common records

--- fetch order details along with the product name and price
select o.ord_id, o.ord_type, o.ord_date, p.prod_id, p.prod_name, p.price
from orders o inner join product p
on o.ord_id = p.prod_id;

--- total revenue generated by each product
select p.prod_name, count(o.ord_id), sum(price)
from product p inner join orders o
on p.prod_id = o.prod_id
group by p.prod_name;

--- product that have never been ordered
select p.prod_name, p.price 
from product p left outer join orders o
on p.prod_id = o.ord_id
where o.ord_id is null 
;

--- Products with more repeat orders than new orders
select p.prod_name, count(*)
from product p inner join orders o
on p.prod_id = o.prod_id
where o.ord_type = 'repeatOrder'
group by p.prod_name
order by count(*) desc
limit 1
;

