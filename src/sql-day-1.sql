--- create a function that takes the product name as input and returns the price
create or replace function product_price_info(prod_nm varchar(2))
returns int
as $$
declare prod_price int;
begin
select price into prod_price from product where prod_name = prod_nm;
return prod_price;
end;
$$ language plpgsql;

select product_price_info('A');

--- create a function that return a table 
