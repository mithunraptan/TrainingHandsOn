--write a procedure that takes prod id and apply discounted price on that product
create or replace procedure discounted_price(prd_id int, discounted_price int)
as $$
begin
update product set price = price - (price*discounted_price)/100 where prod_id = prd_id;
end;
$$ language plpgsql;

call discounted_price(4,10);



